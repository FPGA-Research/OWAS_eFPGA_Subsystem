#!/usr/bin/env python3
"""Write a copy of the eFPGA LEF whose TopMetal1 obstruction matches the GDS.

The fabric LEF has one TopMetal1 OBS over the whole FLUT field, but the GDS leaves
horizontal bands free, which the top PDN uses. Magic reads the LEF for extraction and
flags every stripe in a band as an illegal overlap. This splits the OBS so that every
free band at least --min-channel high stays open; the rest of the LEF is unchanged.

Run by librelane/efpga_subsystem_top/Makefile (needs the klayout Python module).
"""
import argparse
import re
import sys

import klayout.db as db

TM1_LAYER = "TopMetal1"
# IHP SG13 GDS layers: TopMetal1 126, TopVia1 125 (drawing 0, pin 2)
GDS_LAYERS = {125, 126}
GDS_DATATYPES = {0, 2}


def free_channels(gds, cell, box, min_h):
    ly = db.Layout()
    ly.read(gds)
    top = ly.cell(cell)
    if top is None:
        sys.exit(f"cell {cell} not found in {gds}")
    dbu = ly.dbu
    obs = db.Region(db.DBox(*box).to_itype(dbu))
    shapes = db.Region()
    for li in ly.layer_indexes():
        info = ly.get_info(li)
        if info.layer in GDS_LAYERS and info.datatype in GDS_DATATYPES:
            shapes += db.Region(top.begin_shapes_rec(li))
    shapes = (shapes & obs).merged()

    covered = []
    for b, t in sorted((p.bbox().bottom, p.bbox().top) for p in shapes.each()):
        if covered and b <= covered[-1][1]:
            covered[-1][1] = max(covered[-1][1], t)
        else:
            covered.append([b, t])
    y0, y1 = obs.bbox().bottom, obs.bbox().top
    free, y = [], y0
    for b, t in covered:
        if b > y:
            free.append((y, b))
        y = max(y, t)
    if y < y1:
        free.append((y, y1))
    min_dbu = round(min_h / dbu)
    return [(b * dbu, t * dbu) for b, t in free if t - b >= min_dbu], dbu


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--lef", required=True)
    ap.add_argument("--gds", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--cell", default="eFPGA")
    ap.add_argument(
        "--min-channel",
        type=float,
        default=8.0,
        help="open only free channels at least this high (um); 8 = one VDD/VSS "
        "stripe pair (2 + 4 + 2)",
    )
    args = ap.parse_args()

    lines = open(args.lef).read().split("\n")
    # Find the OBS section of the macro and its single TopMetal1 RECT
    in_obs, layer, hit = False, None, None
    for i, line in enumerate(lines):
        s = line.strip()
        if s == "OBS":
            in_obs = True
        elif in_obs and s == "END":
            in_obs = False
        elif in_obs and s.startswith("LAYER"):
            layer = s.split()[1]
        elif in_obs and layer == TM1_LAYER and s.startswith("RECT"):
            if hit is not None:
                sys.exit("more than one TopMetal1 OBS RECT: already processed?")
            hit = i
    if hit is None:
        sys.exit("no TopMetal1 OBS RECT found")
    x0, y0, x1, y1 = map(float, re.findall(r"[-\d.]+", lines[hit])[:4])

    channels, _ = free_channels(args.gds, args.cell, (x0, y0, x1, y1), args.min_channel)
    indent = lines[hit][: len(lines[hit]) - len(lines[hit].lstrip())]
    rects, y = [], y0
    for b, t in channels:
        if b > y:
            rects.append((y, b))
        y = t
    if y < y1:
        rects.append((y, y1))
    new = [f"{indent}RECT {x0:.3f} {b:.3f} {x1:.3f} {t:.3f} ;" for b, t in rects]
    lines[hit : hit + 1] = new

    header = (
        f"# Generated by scripts/efpga_tm1_obs_lef.py: TopMetal1 OBS "
        f"split into {len(rects)} rects, {len(channels)} free channels "
        f">= {args.min_channel} um open (from the macro GDS)."
    )
    with open(args.out, "w") as f:
        f.write(header + "\n" + "\n".join(lines))
    print(f"{len(channels)} channels open, {len(rects)} TopMetal1 OBS rects -> {args.out}")
    for b, t in channels[:6]:
        print(f"  open {b:.3f} .. {t:.3f}")


if __name__ == "__main__":
    main()
